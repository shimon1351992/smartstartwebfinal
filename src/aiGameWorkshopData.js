export function buildWorkshopInitialPrompt({
  gameName = '',
  gameplay = '',
  moodTheme = GAME_MOOD_THEMES[0],
  winMode = GAME_WIN_MODES[0],
  winDetail = ''
}) {
  const finalName = (gameName || 'המשחק האלוף שלי').trim();
  const finalGameplay =
    (gameplay || 'משחק ארקייד מהיר וכיפי עם תנועה חלקה, מכשולים ואובייקטים לאיסוף').trim();
  const finalWinDetail = (winDetail || winMode.defaultDetail).trim();

  return [
    `פעל כמפתח משחקי אינדי בכיר. בנה לי משחק דפדפן יפהפה, חלק ומודרני בקובץ HTML אחד שלם (מוכן לתצוגה חיה ב-Canvas) בעברית (dir="rtl") עם Tailwind CSS וגופן Heebo בשם "${finalName}".`,
    `איך משחקים: ${finalGameplay}.`,
    `עיצוב ואווירה: סגנון ${moodTheme.label} (${moodTheme.desc}), עם מסך פתיחה מרהיב הכולל הוראות מקשים קצרות וכפתור גדול "🚀 התחל משחק", אפקטי חלקיקים ולוח ניקוד/זמן ברור למעלה.`,
    `איך מנצחים / שוברים שיא: ${finalWinDetail}. ${winMode.promptRule}`,
    `אל תשתמש ב-alert של הדפדפן — כל ההודעות והמסכים יהיו מעוצבים בתוך המשחק, והקפד שהמשחק יתאים בגודלו למסך בלי גלילה.`
  ].join('\n');
}

export function buildCustomUpgradePrompt(gameName = 'המשחק שלי', rawIdea = '') {
  const cleanName = (gameName || 'המשחק שלי').trim();
  const cleanIdea = String(rawIdea || '').trim();
  if (!cleanIdea) return '';
  return [
    `שמור על כל מה שכבר עובד במשחק "${cleanName}" ואל תמחק שום פיצ׳ר או עיצוב קיים.`,
    `הוסף למשחק את השדרוג / המכשול המיוחד הבא בצורה מרשימה, חלקה וכיפית:`,
    `"${cleanIdea}"`,
    `ודא שזה משתלב יפה בעיצוב המשחק, כולל אפקט ויזואלי וצליל קצר ב-Web Audio API, ונשאר הוגן ומהנה לתלמידים שיבואו לשחק במשחק שלי בטורניר!`
  ].join('\n');
}
